const test = require('node:test');
const assert = require('node:assert/strict');
const { Miniflare, convertV4MiniflareOptions } = require('miniflare');
const { build } = require('esbuild');

test('共通ランキング：公開閲覧、暗証番号なしの紙登録、重複防止、区分、永続化、途中終了の権限と同期', async t => {
  const bundle = await build({ entryPoints: ['./worker.mjs'], bundle: true, format: 'esm', write: false, platform: 'browser' });
  const mf = new Miniflare(convertV4MiniflareOptions({ name: 'ranking-test', modules: true, script: bundle.outputFiles[0].text,
    compatibilityDate: '2026-10-11', durableObjects: { ROOMS: { className: 'GameRoom', useSQLite: true } } }));
  t.after(() => mf.dispose());
  async function api(path, input, token) {
    const response = await mf.dispatchFetch(`http://localhost/api/${path}`, { method: input ? 'POST' : 'GET',
      headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: input ? JSON.stringify(input) : undefined });
    return { status: response.status, ...await response.json() };
  }
  assert.deepEqual((await api('rankings')).entries, []);
  const paper = { id: 'paper-test', name: '紙の参加者', money: -500, audience: 'child' };
  assert.equal((await api('rankings/paper', { ...paper, money: 1.5 })).status, 400);
  assert.equal((await api('rankings/paper', paper)).status, 200);
  await api('rankings/paper', paper);
  await api('rankings', { id: 'solo-test', name: '個人', money: 120000, audience: 'adult' });
  let entries = (await api('rankings')).entries;
  assert.equal(entries.length, 2); assert.equal(entries[0].money, 120000);
  const update = { id: 'paper-paper-test', name: '変更した名前', money: 150000 };
  for (const invalid of [{ ...update, name: ' ' }, { ...update, money: 1.5 }, { ...update, id: '' }]) {
    assert.equal((await api('admin/rankings/update', invalid)).status, 400);
  }
  assert.equal((await api('admin/rankings/update', { ...update, id: 'missing' })).status, 404);
  const updated = await api('admin/rankings/update', update);
  assert.equal(updated.status, 200);
  assert.equal(updated.entries[0].name, update.name);
  assert.equal(updated.entries[0].money, update.money);
  assert.equal(updated.entries[0].audience, 'child');
  await api('rankings/paper', paper);
  entries = (await api('rankings')).entries;
  assert.equal(entries[0].name, update.name);
  assert.equal(entries[0].money, update.money);
  await mf.unsafeEvictDurableObject('ranking-test', 'GameRoom', { name: 'event-rankings' });
  assert.deepEqual((await api('rankings')).entries, entries);
  assert.equal((await api('admin/rankings/delete', { id: '' })).status, 400);
  assert.equal((await api('admin/rankings/delete', { id: 'missing' })).status, 404);
  assert.equal((await api('admin/rankings/delete', { id: 'paper-paper-test' })).entries.length, 1);
  assert.equal((await api('admin/rankings/delete', { id: 'paper-paper-test' })).status, 200);
  await mf.unsafeEvictDurableObject('ranking-test', 'GameRoom', { name: 'event-rankings' });
  assert.equal((await api('rankings/paper', paper)).entries.length, 1);
  assert.equal((await api('rankings')).entries[0].id, 'solo-solo-test');
  // 以降の既存検証用に、別の記録として登録します。
  await api('rankings/paper', { ...paper, id: 'paper-replacement' });
  const host = await api('rooms', { name: 'ホスト', audience: 'child' });
  const route = `rooms/${host.room.code}`;
  const guest = await api(`${route}/join`, { name: '参加者' });
  assert.equal((await api(`${route}/ranking`, {}, host.token)).status, 409);
  async function connect(token) {
    const response = await mf.dispatchFetch(`http://localhost/api/${route}/socket?token=${token}`, { headers: { Upgrade: 'websocket' } });
    const ws = response.webSocket, queue = [], waiting = [];
    ws.addEventListener('message', event => { const value = JSON.parse(event.data); waiting.length ? waiting.shift()(value) : queue.push(value); });
    ws.accept();
    return { ws, next: () => queue.length ? Promise.resolve(queue.shift()) : new Promise(resolve => waiting.push(resolve)) };
  }
  const a = await connect(host.token), b = await connect(guest.token);
  let state = (await a.next()).room; await b.next();
  a.ws.send(JSON.stringify({ type: 'start', revision: state.revision }));
  state = (await a.next()).room; await b.next();
  b.ws.send(JSON.stringify({ type: 'finish', revision: state.revision }));
  assert.equal((await b.next()).type, 'error'); await b.next(); await a.next();
  a.ws.send(JSON.stringify({ type: 'finish', revision: state.revision }));
  assert.equal((await a.next()).room.status, 'finished');
  assert.equal((await b.next()).room.status, 'finished');
  assert.equal((await api(`${route}/ranking`, {})).status, 403);
  entries = (await api(`${route}/ranking`, {}, guest.token)).entries;
  assert.equal(entries.length, 4);
  assert.equal((await api(`${route}/ranking`, {}, host.token)).entries.length, 4);
  const batch = { entries: [
    { id: 'batch-child', name: '子供の参加者', money: 300, audience: 'child', source: 'グループ' },
    { id: 'batch-adult', name: '大人の参加者', money: 400, audience: 'adult', source: 'ひとり' },
  ] };
  assert.equal((await api('rankings/paper', { ...batch, entries: [batch.entries[0], { ...batch.entries[1], money: 0.5 }] })).status, 400);
  assert.equal((await api('rankings')).entries.length, 4);
  assert.equal((await api('rankings/paper', batch)).entries.length, 6);
  const saved = (await api('rankings')).entries;
  assert.equal(saved.find(p => p.id === 'paper-batch-child').source, 'グループ');
  assert.equal(saved.find(p => p.id === 'paper-batch-adult').source, 'ひとり');
  assert.equal((await api('rankings/paper', { ...paper, source: 'その他' })).status, 400);
  assert.equal((await api('rankings/paper', batch)).entries.length, 6);
  assert.equal((await api('groups/9/create', { name: '範囲外', audience: 'child' })).status, 404);
  assert.equal((await api('groups/1/join', { name: '未作成' })).status, 404);
  const emptyGroups = (await api('groups')).groups;
  assert.equal(emptyGroups.length, 8);
  assert.ok(emptyGroups.every(group => group.status === 'empty' && group.count === 0));
  const groupHost = await api('groups/1/create', { name: 'グループホスト', audience: 'child' });
  assert.equal(groupHost.status, 201);
  assert.equal(groupHost.room.group, 1);
  assert.equal((await api('groups/1/create', { name: '上書き', audience: 'adult' })).status, 409);
  const groupGuest = await api('groups/1/join', { name: 'グループ参加者' });
  assert.equal(groupGuest.room.code, groupHost.room.code);
  assert.equal(groupGuest.room.players.length, 2);
  const waitingGroup = (await api('groups')).groups[0];
  assert.deepEqual(waitingGroup, { group: 1, status: 'waiting', count: 2, audience: 'child' });
  assert.equal(JSON.stringify(waitingGroup).includes(groupHost.token), false);
  const otherGroup = await api('groups/8/create', { name: '別グループ', audience: 'adult' });
  assert.equal(otherGroup.room.group, 8);
  assert.notEqual(otherGroup.room.code, groupHost.room.code);
  await mf.unsafeEvictDurableObject('ranking-test', 'GameRoom', { name: 'group-1' });
  assert.equal((await api('groups/1/join', { name: '再起動後の参加者' })).room.code, groupHost.room.code);
  const groupSocketResponse = await mf.dispatchFetch(`http://localhost/api/rooms/${groupHost.room.code}/socket?token=${groupHost.token}`, { headers: { Upgrade: 'websocket' } });
  const groupSocket = groupSocketResponse.webSocket;
  const messages = [], waiters = [];
  groupSocket.addEventListener('message', event => {
    const data = JSON.parse(event.data);
    waiters.length ? waiters.shift()(data) : messages.push(data);
  });
  groupSocket.accept();
  const nextGroup = () => messages.length ? Promise.resolve(messages.shift()) : new Promise(resolve => waiters.push(resolve));
  let groupState = (await nextGroup()).room;
  groupSocket.send(JSON.stringify({ type: 'start', revision: groupState.revision }));
  groupState = (await nextGroup()).room;
  assert.equal((await api('groups')).groups[0].status, 'playing');
  assert.equal((await api('groups/1/join', { name: '開始後' })).status, 409);
  const adminGroups = (await api('admin/groups')).groups;
  assert.equal(adminGroups[0].code, groupHost.room.code);
  assert.equal(adminGroups[0].status, 'playing');
  assert.equal(JSON.stringify(adminGroups).includes(groupHost.token), false);
  assert.equal((await api('admin/groups/2/finish', { code: '000000' })).status, 404);
  assert.equal((await api('admin/groups/1/finish', { code: 'wrong' })).status, 409);
  assert.equal((await api('admin/groups/1/finish', { code: groupHost.room.code })).status, 200);
  assert.equal((await nextGroup()).room.status, 'finished');
  assert.equal((await api('groups')).groups[0].status, 'finished');
  const reused = await api('groups/1/create', { name: '次のホスト', audience: 'adult' });
  assert.equal(reused.status, 201);
  assert.notEqual(reused.room.code, groupHost.room.code);
  assert.equal(reused.room.audience, 'adult');
  assert.equal((await api('admin/groups/1/finish', { code: groupHost.room.code })).status, 409);
  assert.equal((await api('groups')).groups[0].status, 'waiting');
  assert.equal((await api('admin/groups/1/finish', { code: reused.room.code })).status, 200);
  assert.equal((await api('admin/groups/1/finish', { code: reused.room.code })).status, 200);
  assert.equal((await api('groups')).groups[0].status, 'finished');
  assert.equal((await api(`rooms/${groupHost.room.code}`, null, groupHost.token)).room.status, 'finished');
  groupSocket.close();
  const leavingHost = await api('groups/4/create', { name: '退出ホスト', audience: 'child' });
  const leavingRoute = `rooms/${leavingHost.room.code}`;
  const leavingSecond = await api('groups/4/join', { name: '次のホスト' });
  const leavingThird = await api('groups/4/join', { name: '最後の参加者' });
  async function watchMember(token) {
    const response = await mf.dispatchFetch(`http://localhost/api/${leavingRoute}/socket?token=${token}`, { headers: { Upgrade: 'websocket' } });
    const ws = response.webSocket, queue = [], waiting = [];
    ws.addEventListener('message', event => { const data = JSON.parse(event.data); waiting.length ? waiting.shift()(data) : queue.push(data); });
    ws.accept();
    return { ws, next: () => queue.length ? Promise.resolve(queue.shift()) : new Promise(resolve => waiting.push(resolve)) };
  }
  const leavingConnection = await watchMember(leavingHost.token);
  const remainingConnection = await watchMember(leavingThird.token);
  let leavingState = (await leavingConnection.next()).room;
  await remainingConnection.next();
  leavingConnection.ws.send(JSON.stringify({ type: 'start', revision: leavingState.revision }));
  leavingState = (await leavingConnection.next()).room; await remainingConnection.next();
  leavingConnection.ws.send(JSON.stringify({ type: 'draw', revision: leavingState.revision }));
  await leavingConnection.next(); await remainingConnection.next();
  assert.equal((await api(`${leavingRoute}/leave`, {})).status, 403);
  assert.equal((await api(`${leavingRoute}/leave`, {}, leavingHost.token)).status, 200);
  assert.equal((await leavingConnection.next()).type, 'left');
  let remainingState = (await remainingConnection.next()).room;
  assert.deepEqual(remainingState.players.map(p => p.name), ['次のホスト', '最後の参加者']);
  assert.equal(remainingState.turn, 0);
  assert.equal(remainingState.yourIndex, 1);
  assert.equal((await api(leavingRoute, null, leavingSecond.token)).room.host, true);
  assert.equal((await api(leavingRoute, null, leavingHost.token)).status, 403);
  assert.equal((await api(`${leavingRoute}/leave`, {}, leavingHost.token)).status, 200);
  await mf.unsafeEvictDurableObject('ranking-test', 'GameRoom', { name: 'group-4' });
  assert.equal((await api('groups')).groups[3].count, 2);
  assert.equal((await api(`${leavingRoute}/leave`, {}, leavingSecond.token)).status, 200);
  remainingState = (await remainingConnection.next()).room;
  assert.equal(remainingState.players.length, 1);
  assert.equal(remainingState.turn, 0);
  assert.equal(remainingState.host, true);
  assert.equal((await api('admin/groups/4/finish', { code: leavingHost.room.code })).status, 200);
  await remainingConnection.next();
  assert.equal((await api(`${leavingRoute}/leave`, {}, leavingThird.token)).status, 200);
  assert.equal((await remainingConnection.next()).type, 'left');
  const emptyAfterLeave = (await api('groups')).groups[3];
  assert.equal(emptyAfterLeave.count, 0);
  assert.equal(emptyAfterLeave.status, 'finished');
  assert.equal((await api('groups/4/create', { name: '再利用', audience: 'child' })).status, 201);
  const alone = await api('groups/5/create', { name: 'ひとりで待機', audience: 'child' });
  assert.equal((await api(`rooms/${alone.room.code}/leave`, {}, alone.token)).status, 200);
  assert.equal((await api('groups')).groups[4].status, 'finished');
  assert.equal((await api('groups/5/create', { name: '新しいホスト', audience: 'child' })).status, 201);
  a.ws.close(); b.ws.close();
});
